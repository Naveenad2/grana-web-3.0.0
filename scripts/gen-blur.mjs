// Regenerates src/lib/blur-data.ts: a tiny blurred preview for every photo in public/images,
// shown while the real image loads so photos never pop in from an empty box.
// Run after adding or replacing photos:  npm run blur
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const PUBLIC = path.join(ROOT, "public");

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (/\.(jpe?g|png|webp)$/i.test(entry.name)) out.push(full);
  }
  return out;
}

const files = (await walk(path.join(PUBLIC, "images"))).sort();
const entries = [];
for (const file of files) {
  const buf = await sharp(file).resize(10, 10, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
  const src = "/" + path.relative(PUBLIC, file).split(path.sep).join("/");
  entries.push(`  "${src}": "data:image/webp;base64,${buf.toString("base64")}",`);
}

const body = `// Generated by scripts/gen-blur.mjs. Do not edit by hand: run \`npm run blur\` instead.

export const blurData: Record<string, string> = {
${entries.join("\n")}
};
`;
await writeFile(path.join(ROOT, "src/lib/blur-data.ts"), body);
console.log(`blur placeholders: ${entries.length} images, ${(body.length / 1024).toFixed(1)} KB`);
